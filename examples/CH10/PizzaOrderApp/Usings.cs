//
//  A "global using" makes a namespace available to EVERY FILE
//  in the project — no need to repeat "using System.Windows.Forms;"
//  at the top of each .cs file.
//
//  Convention: store global usings in a file named Usings.cs
//  at the root of the project.  The file name doesn't matter
//  technically, but Usings.cs is the accepted convention.
// ============================================================

